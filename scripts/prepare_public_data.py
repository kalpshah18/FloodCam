#!/usr/bin/env python
"""Public segmentation data: instructions, verification, manifest.

Default (no flags): downloads NOTHING. Prints, per enabled dataset, a source placeholder,
a licence checklist, the folder layout expected under data/public/, and what you must do.

  python scripts/prepare_public_data.py
  python scripts/prepare_public_data.py --verify     # after you downloaded + checked licences

--verify:
  * parses each dataset's OWN label file and fails loudly if a mapped class is absent
  * builds data/public/seg_manifest.jsonl (gitignored; derivable)
  * writes data/splits/public_seg_splits.json (IDs only, committed)
  * writes data/public/DATASETS.md (dataset, licence status, file hashes, counts; committed)
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from collections import Counter
from datetime import date
from pathlib import Path

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT / "src"))

from floodcam.seg.classmap import ClassMapError, load_classmap  # noqa: E402
from floodcam.seg.datasets import (  # noqa: E402
    DatasetLayoutError,
    build_public_manifest,
    file_sha256,
    write_public_splits,
    write_seg_manifest,
)

SOURCE_URLS = {
    "ade20k": "<ADE20K / SceneParsing download page - fill in and record the version>",
    "cocostuff": "<COCO-Stuff download page - fill in and record the version>",
    "floodnet": "<FloodNet download page - fill in and record the version>",
}


def print_instructions(cm, data_root: Path) -> None:
    print("No data is downloaded by this script. Do these steps yourself.\n")
    for spec in cm.enabled_datasets() or []:
        _print_spec(spec, data_root)
    off = [s for s in cm.datasets.values() if not s.enabled]
    for spec in off:
        print(f"[disabled] {spec.key}: {spec.domain_gap_note or 'set enabled: true to use'}")
    if cm.negatives.enabled:
        n = cm.negatives
        print(f"\n[negatives] {data_root / n.root}/images/<sequence>/*.jpg")
        print(f"            optional masks: {data_root / n.root}/masks/<sequence>/*.png")
        print("            No people or private locations. Missing mask = all background.")
    print("\nThen: python scripts/prepare_public_data.py --verify")


def _print_spec(spec, data_root: Path) -> None:
    print(f"=== {spec.key} ===")
    print(f"  source URL : {SOURCE_URLS.get(spec.key, '<fill in>')}")
    print("  licence checklist (tick each before use):")
    for item in (
        "read the licence text at the source (not a third-party summary)",
        "research / course-project use is permitted",
        "redistribution terms understood (we never commit images)",
        "citation requirement noted in AI_USE.md / the paper",
    ):
        print(f"    [ ] {item}")
    print(f"  licence note in config: {spec.license_note} (license_verified={spec.license_verified})")
    base = data_root / spec.root
    print("  expected layout:")
    for split, sdir in spec.split_dirs.items():
        print(f"    {base / spec.image_dir.format(split=sdir)}/<name>{'|'.join(spec.image_ext)}")
        print(f"    {base / spec.mask_dir.format(split=sdir)}/<name>{spec.mask_ext}")
    if spec.label_file:
        print(f"    {base / spec.label_file}   (the dataset's own class table, format "
              f"{spec.label_format})")
    print("  you must: download from the source, extract / rearrange (move or symlink) into "
          "the layout above.")
    print(f"  mapped water classes: {spec.water_class_names or spec.water_class_ids or 'mask>0'} "
          "(verified against the label file by --verify)\n")


def _dir_hash(paths: list[Path]) -> str:
    h = hashlib.sha256()
    for p in sorted(paths):
        h.update(p.name.encode())
        h.update(file_sha256(p).encode())
    return h.hexdigest()


def verify(cm, data_root: Path, seed: int, splits_out: Path) -> int:
    try:
        rows, water_ids = build_public_manifest(cm, data_root, seed)
    except (ClassMapError, DatasetLayoutError) as exc:
        print(f"VERIFY FAILED: {exc}", file=sys.stderr)
        return 1
    manifest_path = data_root / "seg_manifest.jsonl"
    sha = write_seg_manifest(rows, water_ids, manifest_path)
    write_public_splits(rows, sha, splits_out, seed)

    counts = Counter((r.source, r.split) for r in rows)
    lines = [
        "# Public segmentation datasets",
        "",
        f"Generated by `scripts/prepare_public_data.py --verify` on {date.today().isoformat()}.",
        f"Manifest sha256: `{sha}`. Images are never committed; this file is.",
        "",
        "| dataset | water classes (verified) | license_verified | licence note | "
        "train | val | label-file sha256 | all-file-hash |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for spec in cm.enabled_datasets():
        ds_root = data_root / spec.root
        label_hash = file_sha256(ds_root / spec.label_file)[:16] if spec.label_file else "-"
        files = [data_root / r.image_path for r in rows if r.source == spec.key]
        lines.append(
            f"| {spec.key} | {spec.water_class_names or spec.water_class_ids or 'mask>0'}"
            f" -> ids {water_ids[spec.key]} | {spec.license_verified} | {spec.license_note} | "
            f"{counts[(spec.key, 'train')]} | {counts[(spec.key, 'val')]} | {label_hash} | "
            f"{_dir_hash(files)[:16]} |"
        )
    if cm.negatives.enabled:
        neg_files = [data_root / r.image_path for r in rows if r.source == "negatives"]
        lines.append(
            f"| negatives | (empty/partial masks) | n/a | own recordings | "
            f"{counts[('negatives', 'train')]} | {counts[('negatives', 'val')]} | - | "
            f"{_dir_hash(neg_files)[:16] if neg_files else '-'} |"
        )
    unverified = [s.key for s in cm.enabled_datasets() if not s.license_verified]
    if unverified:
        lines += ["", f"**WARNING: licence not marked verified for: {', '.join(unverified)}.**"]
    (data_root / "DATASETS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Verified {len(rows)} images. Manifest: {manifest_path}")
    print(f"Wrote {splits_out} and {data_root / 'DATASETS.md'}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--class-map", type=Path, default=ROOT / "configs" / "seg_classmap.yaml")
    ap.add_argument("--data-root", type=Path, default=ROOT / "data" / "public")
    ap.add_argument("--splits-out", type=Path,
                    default=ROOT / "data" / "splits" / "public_seg_splits.json")
    ap.add_argument("--verify", action="store_true")
    ap.add_argument("--seed", type=int, default=42)
    a = ap.parse_args()
    cm = load_classmap(a.class_map)
    if not a.verify:
        print_instructions(cm, a.data_root)
        return 0
    return verify(cm, a.data_root, a.seed, a.splits_out)


if __name__ == "__main__":
    sys.exit(main())
